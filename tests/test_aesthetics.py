class CurrentNameTests(unittest.TestCase):
    def test_ignores_regex_looking_strings(self):
        import tempfile
        from pathlib import Path
        from ihc import aesthetics
        with tempfile.TemporaryDirectory() as d:
            decoy = Path(d) / "a.nix"; decoy.write_text('x = "profileName = \\"(?<name>[^,]+)\\"";\n')
            real = Path(d) / "b.nix"; real.write_text('profileName = "sunset";\n')
            self.assertEqual(aesthetics.current_name([decoy, real]), "sunset")
